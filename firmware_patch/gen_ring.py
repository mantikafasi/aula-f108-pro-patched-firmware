"""Generate ring_table.h: 28x28 lookup for the usage rings.
value < 100: ring pixel, filled when value < percent (clockwise from 12 o'clock); 254: inside the ring; 255: outside."""
import math

N, C, R_IN, R_OUT = 28, 14.0, 9.0, 13.3
rows = []
for y in range(N):
    row = []
    for x in range(N):
        dx, dy = x + .5 - C, y + .5 - C
        d = math.hypot(dx, dy)
        if d < R_IN: row.append(254)
        elif d > R_OUT: row.append(255)
        else:
            a = math.atan2(dx, -dy) % (2 * math.pi)       # 0 at the top, clockwise
            row.append(min(99, int(a / (2 * math.pi) * 100)))
    rows.append(row)
body = ",\n".join("    " + ",".join("%d" % v for v in r) for r in rows)
open("ring_table.h", "w").write("/* generated by gen_ring.py */\nstatic const u8 RING[28 * 28] = {\n%s\n};\n" % body)
print("ring_table.h written")
